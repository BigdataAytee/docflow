/** Flattened once, at load, because every lookup goes the other way. */
const COUNTRY_BY_ZONE: ReadonlyMap<string, string> = new Map(
  Object.entries(ZONES_BY_COUNTRY).flatMap(([country, zones]) =>
    zones.map((zone) => [zone.toLowerCase(), country] as const),
  ),
)

/**
 * The country an IANA zone belongs to, or undefined when it is not one this
 * table knows.
 *
 * UTC, GMT and the `Etc/*` zones are deliberately absent: they describe an
 * OFFSET rather than a place, and a device reporting one is telling you it
 * does not know where it is. Reading a country out of that would be inventing
 * the one fact the whole lookup exists to establish.
 */
export function countryForTimeZone(zone: string | undefined): string | undefined {
  if (zone === undefined) return undefined
  return COUNTRY_BY_ZONE.get(zone.trim().toLowerCase())
}

/*
 * GS (South Georgia) and TF (the French Southern Territories) are absent on
 * purpose. They have zones and no permanent population, no currency in the
 * country table and no entry in the picker — so detecting one would hand the
 * app a country it cannot offer. Leaving them out makes detection fall
 * through to the language tag, which is the right answer for a research
 * station.
 */

