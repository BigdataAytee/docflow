/**
 * IANA time zone → ISO 3166-1 country (§D, §R).
 *
 * WHY THIS EXISTS. The app guessed a business's country from
 * `navigator.language`, and a language tag is not a location. A trader in Ifo
 * whose phone is set to English reports `en-US`, or bare `en` — so the guess
 * was "United States", or nothing at all, and the documents came out called
 * "Packing slip". §D hangs terminology, currency, bank fields, tax vocabulary
 * and date format off the country, so one bad signal moved all five.
 *
 * The time zone is the signal that actually describes where the device IS. It
 * is set by the network or by the owner, it survives a handset being in
 * English, it needs no permission prompt, no network call and no plugin, and
 * it reads identically in the browser and in the Capacitor WebView —
 * `Intl.DateTimeFormat().resolvedOptions().timeZone`. Africa/Lagos is Nigeria
 * whatever language the phone speaks.
 *
 * WHAT IT IS NOT. This is not a positioning system and does not try to be. A
 * zone shared by several countries resolves to the one it is NAMED for, and
 * anybody the guess is wrong for changes the country in Settings — a picker
 * that is already there, already pre-filled, and the one choice §D asks for.
 * A guess that is right for almost everybody and correctable by everybody is
 * the whole ambition.
 *
 * The data is IANA's own zone table. Aliases and the deprecated short zones
 * are included where a device might still report one, because the point is to
 * recognise what real phones say rather than what they ought to say.
 */

